import { Router } from 'express';
import auth from '../middleware/auth';
import * as controller from '../controllers/collaboratorController';
const router = Router();
router.get('/invite/:token', (req, res, next) => req.headers.authorization ? auth(req, res, next) : next(), controller.inviteMetadata);
router.use(auth);
router.post('/join/:token', controller.requestAccess);
router.post('/:noteId/link', controller.createLink);
router.delete('/:noteId/link', controller.revokeLinks);
router.get('/:noteId/requests', controller.requests);
router.patch('/:noteId/requests/:requestId', controller.decide);
router.get('/:noteId', controller.collaborators);
export default router;
